//
// 口径：步骤与系统的对应关系按真实银行业务链路写；清算时序、限额、
// 手续费等数字为行业通行口径，个别处在文中标明「各行口径不同」。
// 每一步的 moduleId 与 content.ts 全景图模块同 id，点系统名可跳去看
// 该模块的完整讲解（职责边界 / 交互 / 例子 / 误解）。

export interface LedgerLine {
  kind: "借" | "贷" | "注";
  text: string;
  /** 记账主体，如「付款行」「收款行」「发卡行」；缺省不显示。 */
  party?: string;
}

export interface JourneyStep {
  /** 全景图模块 id（与 PANORAMA 中的模块同名同 id）。 */
  moduleId: string;
  /** 这一步的标题，如「核心扣款并冻结待清算资金」。 */
  title: string;
  /** 这一步做什么、账务/数据怎么动。 */
  detail: string;
  /** 这一步失败会怎样：冲正 / 退汇 / 挂账 / 拒绝…… */
  failure: string;
  /** 本步产生的账务分录（借/贷逐行），账务小窗随步骤累积显示。 */
  ledger?: LedgerLine[];
}

